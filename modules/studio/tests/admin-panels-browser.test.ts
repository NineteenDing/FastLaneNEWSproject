import "../../../tests/setup.ts";
import assert from "node:assert/strict";
import { test, after } from "node:test";
import { mkdir } from "node:fs/promises";
import { chromium, expect } from "@playwright/test";
import { config } from "@aihot/backend/config";
import { closeDb } from "@aihot/backend/db";
import { stopBoss } from "@aihot/backend/jobs/queue";
import { sourceResourceFixture } from "./source-resource-fixture.ts";
import { startWebServer } from "../../../apps/web/tests/web-server.ts";

process.env.COLLECT_ENABLED = "false"; config.modelCallsEnabled = false;
const { app, headers } = await sourceResourceFixture();
after(async () => { await app.close(); await stopBoss(); await closeDb(); });
test("丰富示例下侧栏弹窗、历史分栏、搜索、处理状态与统计页面可操作且不整页刷新", async () => {
  assert.equal((await app.inject({ method: "POST", url: "/api/admin/studio/acceptance-examples", headers, payload: {} })).statusCode, 200);
  const referencedTitle = (await app.inject({ url: "/api/admin/studio/drafts?limit=1", headers })).json().rows[0].snapshot.materials[0].title.slice(0, 100);
  const web = await startWebServer(app.server), browser = await chromium.launch(), context = await browser.newContext({ reducedMotion: "reduce" });
  const [name, ...value] = headers.cookie.split("="); await context.addCookies([{ name: name!, value: value.join("="), url: web.origin }]);
  const page = await context.newPage(), errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await mkdir(".impeccable/review", { recursive: true });
  try {
    for (const width of [1440, 390]) {
      await page.setViewportSize({ width, height: 1000 });
      for (const route of ["following", "creators", "intelligence?view=archive", "topics?view=history", "topics/columns", "writing?view=history", "settings/processing", "settings/learning", "settings/backup", "settings/visitors"]) {
        const response = await page.goto(web.origin + "/admin/studio/" + route); assert.equal(response?.status(), 200, route);
        await expect(page.locator("#studio-main")).toBeVisible();
        assert.equal(await page.evaluate("document.documentElement.scrollWidth > innerWidth"), false, `${route}:${width}`);
        await page.screenshot({ path: `.impeccable/review/admin-round2-${route.replaceAll(/[/?=]/g, "-")}-${width}.png` });
      }
      await page.goto(web.origin + "/admin/studio/writing?view=history");
      await page.getByRole("searchbox", { name: "搜索全部稿件", exact: true }).fill("固定参考");
      const matches = page.getByRole("region", { name: "稿件搜索结果", exact: true });
      await expect(matches.getByRole("link").first()).toBeVisible();
      await expect(matches.locator("mark").first()).toHaveText("固定参考");
      await page.getByRole("searchbox", { name: "搜索全部稿件", exact: true }).fill(referencedTitle);
      await expect(matches.getByRole("link").first().locator("p").filter({ hasText: "引用：" }).locator("mark").first()).toHaveText(referencedTitle);
      await page.goto(web.origin + "/admin/studio/following");
      const source = page.locator(".studio-source").first();
      await expect(source.locator("footer button")).toHaveCount(2);
      await source.getByRole("button", { name: "编辑资料", exact: true }).click();
      const dialog = page.getByRole("dialog"); await expect(dialog).toBeVisible();
      await expect(dialog.getByRole("navigation").getByRole("button")).toHaveCount(4);
      await dialog.getByRole("navigation").getByRole("button", { name: "采集设置", exact: true }).click();
      await expect(dialog.getByLabel("采集地址", { exact: true })).toBeVisible();
      await page.keyboard.press("Escape"); await expect(dialog).toHaveCount(0);
      await page.goto(web.origin + "/admin/studio/creators");
      await page.locator(".studio-source").first().getByRole("button", { name: "博主档案", exact: true }).click();
      const collection = page.getByRole("dialog");
      await expect(collection.getByLabel("选择收录作品", { exact: true })).toBeVisible();
      await expect(collection.getByRole("navigation", { name: "收录作品分页", exact: true })).toHaveCount(0);
      await collection.getByRole("button", { name: "热度记录", exact: true }).click();
      const reader = collection.getByRole("region", { name: "作品资料内容", exact: true });
      await expect(reader.getByRole("region", { name: "作品热度变化", exact: true })).toBeVisible();
      assert.equal(await collection.locator(".studio-panel-section:not([hidden])").evaluate(el => (globalThis as unknown as { getComputedStyle(node: unknown): { overflowY: string } }).getComputedStyle(el).overflowY), "hidden", "弹窗外层不重复滚动");
      await reader.hover(); await page.mouse.wheel(0, 550);
      await expect.poll(() => reader.evaluate(el => (el as unknown as { scrollTop: number }).scrollTop)).toBeGreaterThan(0);
      await dialog.getByRole("navigation").getByRole("button", { name: "档案与表达模式", exact: true }).click();
      await expect(dialog.getByRole("heading", { name: "表达模式", exact: true })).toBeVisible();
      assert.equal(await dialog.locator("details:not([open])").count(), 0);
      await page.keyboard.press("Escape");
      let documents = 0; const watch = (request: { resourceType(): string }) => { if (request.resourceType() === "document") documents++; };
      page.on("request", watch);
      await page.getByRole("navigation", { name: "工作台导航" }).getByRole("link", { name: "选题台", exact: true }).click();
      await expect(page.locator(".studio-topic-direction-button").first()).toBeVisible();
      page.off("request", watch); assert.equal(documents, 0, "档案退出后导航不触发文档刷新");
      await page.goto(web.origin + "/admin/studio/topics/columns");
      await page.getByRole("button", { name: "查看规则", exact: true }).first().click();
      await dialog.getByRole("navigation").getByRole("button", { name: "规则版本", exact: true }).click();
      await expect(dialog.getByLabel("规则历史版本", { exact: true })).toBeVisible(); await page.keyboard.press("Escape");
      await page.goto(web.origin + "/admin/studio/settings/processing");
      await page.getByRole("button", { name: "查看状态", exact: true }).click();
      await dialog.getByRole("navigation").getByRole("button", { name: "已收录的当期材料", exact: true }).click();
      await expect(dialog.getByRole("navigation", { name: "批次材料分页", exact: true })).toBeVisible();
      assert.equal(await dialog.locator("details:not([open])").count(), 0); await page.keyboard.press("Escape");
      await page.getByRole("button", { name: "检查期次", exact: true }).click();
      await dialog.getByRole("navigation").getByRole("button", { name: "历史期次", exact: true }).click();
      await dialog.getByRole("complementary", { name: "历史期次日期", exact: true }).getByRole("link").first().click();
      await expect(dialog).toHaveCount(0);
      await expect(page).toHaveURL(/batch=/);
      await page.getByRole("button", { name: "查看状态", exact: true }).click();
      await dialog.getByRole("navigation").getByRole("button", { name: "已收录的当期材料", exact: true }).click();
      await expect(dialog.getByRole("navigation", { name: "批次材料分页", exact: true })).toBeVisible();
      await page.keyboard.press("Escape");
      await page.goto(web.origin + "/admin/studio/settings/learning");
      if (width === 390) await page.getByRole("button", { name: "规则学习", exact: true }).click();
      const learning = page.getByRole("region", { name: "栏目规则学习", exact: true });
      await learning.getByRole("button", { name: "样本与原规则", exact: true }).click();
      const content = learning.locator(".studio-learning-workspace > .studio-scroll-region");
      await content.hover(); await page.mouse.wheel(0, 550);
      await expect.poll(() => content.evaluate(el => (el as unknown as { scrollTop: number }).scrollTop)).toBeGreaterThan(0);
      const refresh = learning.getByRole("button", { name: "刷新学习记录", exact: true });
      const before = await refresh.boundingBox();
      await learning.getByRole("button", { name: "下一页", exact: true }).click();
      await expect(learning.getByRole("navigation", { name: "规则学习记录分页", exact: true })).toContainText("第 2 页");
      await expect(refresh).toBeEnabled();
      const after = await refresh.boundingBox();
      assert.equal(Math.round(after!.y), Math.round(before!.y), "学习翻页不移动刷新按钮");
    }
    assert.deepEqual(errors, []);
  } finally { await context.close(); await browser.close(); await web.stop(); }
});
