import '../../../tests/setup.ts';
import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {sourceResourceFixture} from './source-resource-fixture.ts';
import {closeDb} from '@aihot/backend/db';
import {getBoss,stopBoss} from '@aihot/backend/jobs/queue';
import {SERVER_MODULES} from '@aihot/site/modules/server';
const {app,headers}=await sourceResourceFixture();
after(async()=>{await app.close();await stopBoss();await closeDb();});
test('管理员指定目录生成程序配置数据库素材整体副本，原日常目录不变且不复制模型缓存',async t=>{
  const destination=await mkdtemp(join(tmpdir(),'fastlane-portable-test-'));
  t.after(()=>rm(destination,{recursive:true,force:true}));
  const previous=process.env.STUDIO_BACKUP_DIRECTORY;delete process.env.STUDIO_BACKUP_DIRECTORY;
  t.after(()=>{if(previous===undefined)delete process.env.STUDIO_BACKUP_DIRECTORY;else process.env.STUDIO_BACKUP_DIRECTORY=previous;});
  const url='/api/admin/studio/backup';
  const sent=await app.inject({method:'POST',url,headers,payload:{scope:'portable',destination}});
  assert.equal(sent.statusCode,200,sent.body);
  const queue=SERVER_MODULES.find(m=>m.name==='studio')!.queues!.find(q=>q.name==='studio.backup.capture')!;
  const boss=await getBoss(),[job]=await boss.fetch(queue.name);assert.ok(job);
  await queue.run([job.data] as never[]);await boss.complete(queue.name,job.id);
  const status=(await app.inject({url,headers})).json();assert.equal(status.state,'completed');assert.equal(status.configured,false);assert.equal(status.protected,false);
  assert.ok(!JSON.stringify(status).includes(destination));
  const manifest=JSON.parse(await readFile(join(destination,status.last.id,'manifest.json'),'utf8'));
  assert.equal(manifest.scope,'portable');
  const names=manifest.files.map((file:{name:string})=>file.name);
  for(const file of ['database.dump','program/package.json','program/package-lock.json','program/tsconfig.base.json','program/database/migrations/0001_core.sql','program/modules/studio/server.ts'])assert.ok(names.includes(file),file);
  assert.ok(names.every((name:string)=>!/(?:^|\/)(?:node_modules|\.local|models|pgdata|\.git)(?:\/|$)/.test(name)));
  assert.equal(process.env.STUDIO_BACKUP_DIRECTORY,undefined);
});
