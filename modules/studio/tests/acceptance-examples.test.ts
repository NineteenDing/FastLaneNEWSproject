import "../../../tests/setup.ts";
import assert from "node:assert/strict";
import { after, test } from "node:test";
import { config } from "@aihot/backend/config";
import { closeDb } from "@aihot/backend/db";
import { stopBoss } from "@aihot/backend/jobs/queue";
import { sourceResourceFixture } from "./source-resource-fixture.ts";
import { randomUUID } from "node:crypto";

process.env.COLLECT_ENABLED = "false"; config.modelCallsEnabled = false;
const { app, headers } = await sourceResourceFixture();
after(async () => { await app.close(); await stopBoss(); await closeDb(); });
const base = "/api/admin/studio/acceptance-examples";
test("示例幂等载入到实际页面接口：新闻、七平台、审核方向、独立稿与样本可读，清理后保留用户来源和配置", async () => {
  assert.equal((await app.inject({ method: "POST", url: "/api/admin/sources", headers, payload: { id: "user-owned-source", name: "我的来源保留", kind: "rss", enabled: false, config: { feedUrl: "https://user-owned.example/feed" } } })).statusCode, 200);
  assert.equal((await app.inject({ method: "POST", url: base, payload: {} })).statusCode, 401);
  const added = await app.inject({ method: "POST", url: base, headers, payload: {} });
  assert.equal(added.statusCode, 200, added.body); assert.equal(added.json().active, true);
  const again = await app.inject({ method: "POST", url: base, headers, payload: {} });
  assert.deepEqual(again.json(), added.json());
  const sources = (await app.inject({ url: "/api/admin/studio/news-sources?q=示例&limit=100", headers })).json();
  assert.equal(sources.total, 32); assert.ok(sources.rows.every((r: { enabled: boolean }) => !r.enabled));
  const creators = (await app.inject({ url: "/api/admin/studio/creators?q=示例&limit=100", headers })).json();
  assert.equal(creators.total, 7);
  const materials = (await app.inject({ url: "/api/admin/studio/intelligence?q=示例&limit=100", headers })).json();
  assert.ok(materials.total >= 40);
  const detail = await app.inject({ url: `/api/admin/studio/intelligence/${materials.rows.find((r: { kind: string }) => r.kind === "video").id}`, headers });
  assert.equal(detail.statusCode, 200); assert.ok(detail.json().observations.length > 1); assert.ok(detail.json().comments.length);
  const presentation = (await app.inject({ url: "/api/admin/studio/topic-batches/presentation", headers })).json();
  assert.ok(presentation.batch?.id);
  const review = (await app.inject({ url: `/api/admin/studio/topic-batches/${presentation.batch.id}/review`, headers })).json();
  assert.equal(review.state, "completed"); assert.equal(review.result.directions.length, 9);
  assert.ok(review.summary.includes("示例"));
  const drafts = (await app.inject({ url: "/api/admin/studio/drafts?limit=100", headers })).json();
  assert.ok(drafts.total >= 3);
  const sample = (await app.inject({ url: "/api/admin/studio/language-samples?limit=100", headers })).json();
  assert.ok(sample.total >= 6);
  const removed = await app.inject({ method: "DELETE", url: base, headers, payload: {} });
  assert.equal(removed.statusCode, 200, removed.body); assert.equal(removed.json().active, false);
  assert.equal((await app.inject({ url: "/api/admin/studio/news-sources?q=示例", headers })).json().total, 0);
  assert.equal((await app.inject({ url: "/api/admin/studio/news-sources?q=我的来源保留", headers })).json().total, 1);
  assert.equal((await app.inject({ url: "/api/admin/studio/platform-sessions", headers })).json().rows.filter((s: { state: string }) => s.state !== "missing").length, 0);
});

test("另建稿件引用示例时清理整体拒绝，原稿、示例、设置均保持，学习历史分别分页", async () => {
  assert.equal((await app.inject({ method: "POST", url: base, headers, payload: {} })).statusCode, 200);
  const presentation = (await app.inject({ url: "/api/admin/studio/topic-batches/presentation", headers })).json();
  const id = presentation.batch.id;
  const directions = (await app.inject({ url: `/api/admin/studio/topic-batches/${id}/review`, headers })).json().result.directions;
  const project = await app.inject({ method: "POST", url: "/api/admin/studio/drafts", headers, payload: { requestId: randomUUID(), batchId: id, directionIds: [directions[0].id], title: "用户另建稿，保护保留" } });
  assert.equal(project.statusCode, 200, project.body);
  const first = (await app.inject({ url: "/api/admin/studio/columns/practice/learning?page=1", headers })).json();
  const second = (await app.inject({ url: "/api/admin/studio/columns/practice/learning?page=2", headers })).json();
  assert.equal(first.total, 3); assert.equal(first.hasMore, true); assert.notEqual(first.run.id, second.run.id);
  const result = await app.inject({ method: "DELETE", url: base, headers, payload: {} });
  assert.equal(result.statusCode, 409); assert.ok(result.json().detail.includes("另建稿件"));
  assert.equal((await app.inject({ url: base, headers })).json().active, true);
  assert.equal((await app.inject({ url: `/api/admin/studio/drafts/${project.json().id}`, headers })).json().title, "用户另建稿，保护保留");
  assert.equal((await app.inject({ url: "/api/admin/studio/news-sources?q=我的来源保留", headers })).json().total, 1);
});
